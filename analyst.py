def generate_research_report(market_data: Dict[str, Any]) -> str:
    """Gemini API を呼び出してプロ仕様のレポートを生成する"""
    api_key = os.environ.get("GEMINI_API_KEY")
    if not api_key:
        print("Notice: GEMINI_API_KEY が設定されていないため、サンプルモックレポートを生成します。")
        return generate_mock_report(market_data)

    try:
        from google import genai
        client = genai.Client(api_key=api_key)

        prompt = f"""
以下は本日（{market_data.get('date_str', '')}）の日本株および主要市場データです。
このデータを元に、システム指示に従ってプロ仕様のデイリー・エクイティ・リサーチレポートを作成してください。

【市場データ JSON】
{json.dumps(market_data, ensure_ascii=False, indent=2)}
"""
        response = client.models.generate_content(
            model="gemini-2.5-flash",
            contents=prompt,
            config={"system_instruction": SYSTEM_PROMPT, "temperature": 0.3}
        )
        return response.text
    except Exception as e:
        print(f"Gemini API呼び出し中にエラーが発生しました: {e}。モックレポートにフォールバックします。")
        return generate_mock_report(market_data)


